-- 지역 대표 사진(2026-10-17, docs/api/attraction.md "지역 대표 사진"). 한국관광공사 관광사진 정보 API(공공누리 제1유형) 후보를
-- DRAFT로 넣고, 사람이 지역마다 한 장을 승인한다. APPROVED만 지역 카드 heroImage ②로 나간다.
-- 원천 사진이라 생성물이 아니다. 사진 파일은 원천 URL을 그대로 쓰고 복사하지 않는다.

CREATE TABLE region_hero_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id VARCHAR(5) NOT NULL REFERENCES regions(sig_cd) ON DELETE CASCADE,
    source_system VARCHAR(50) NOT NULL,
    source_content_id VARCHAR(100) NOT NULL,
    image_url VARCHAR(1000) NOT NULL,
    title VARCHAR(255),
    photographer VARCHAR(255),
    photography_location VARCHAR(255),
    photography_month VARCHAR(6),
    source_name VARCHAR(100) NOT NULL,
    source_url VARCHAR(1000),
    license_note VARCHAR(255) NOT NULL,
    candidate_rank INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    reviewed_by VARCHAR(100),
    reviewed_at TIMESTAMP WITHOUT TIME ZONE,
    review_note TEXT,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_region_hero_photos_source UNIQUE (region_id, source_system, source_content_id),
    CONSTRAINT ck_region_hero_photos_status CHECK (status IN ('DRAFT', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_region_hero_photos_url CHECK (image_url LIKE 'https://%'),
    CONSTRAINT ck_region_hero_photos_review CHECK (status = 'DRAFT' OR reviewed_at IS NOT NULL)
);
-- 지역마다 승인된 사진은 한 장
CREATE UNIQUE INDEX uq_region_hero_photos_approved ON region_hero_photos(region_id) WHERE status = 'APPROVED';
CREATE INDEX idx_region_hero_photos_status ON region_hero_photos(status);
