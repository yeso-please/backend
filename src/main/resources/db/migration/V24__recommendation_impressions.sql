-- 추천 노출 기록(2026-10-24, docs/design/recommendation.md §9). 지역 뽑기·코스 생성이 이미 확률 추첨이므로
-- 후보마다 뽑힐 확률을 그대로 남기면, 출시 후 새 추천 방식을 오프라인에서 공정하게 평가(IPS)하고 밴딧으로 학습할 수 있다.
-- 화면·API에는 쓰지 않는다. 회원을 지우면 함께 지운다(행동 기록이므로).
-- candidates: [{"id", "score", "weight", "probability"}] — 지역 뽑기는 sigCd 문자열, 코스는 관광지 ID
-- chosen:     [{"id", "step", "probability"}] — 지역 뽑기는 1건, 코스는 뽑은 순서대로(각 단계의 조건부 확률)

CREATE TABLE recommendation_impressions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    trip_plan_id BIGINT REFERENCES trip_plans(id) ON DELETE SET NULL,
    stage VARCHAR(30) NOT NULL,
    policy VARCHAR(30) NOT NULL,
    applied_conditions JSONB NOT NULL DEFAULT '[]'::jsonb,
    model_version VARCHAR(100),
    template_version INTEGER,
    candidates JSONB NOT NULL,
    chosen JSONB NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_recommendation_impressions_stage CHECK (stage IN ('REGION_DRAW', 'REGION_PRE_DRAW', 'COURSE_GENERATION')),
    CONSTRAINT ck_recommendation_impressions_candidates CHECK (jsonb_typeof(candidates) = 'array'),
    CONSTRAINT ck_recommendation_impressions_chosen CHECK (jsonb_typeof(chosen) = 'array')
);
CREATE INDEX idx_recommendation_impressions_user ON recommendation_impressions(user_id, created_at);
CREATE INDEX idx_recommendation_impressions_stage ON recommendation_impressions(stage, created_at);
