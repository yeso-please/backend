-- 1) 변경 기록 -------------------------------------------------------------------------------------------
ALTER TABLE course_items
    ADD COLUMN origin VARCHAR(20),
    ADD COLUMN changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN changed_by_nickname VARCHAR(50),
    ADD COLUMN replaced_from_attraction_id BIGINT REFERENCES attractions(id) ON DELETE SET NULL,
    ADD COLUMN replaced_from_name VARCHAR(255),
    ADD COLUMN change_note VARCHAR(100),
    ADD COLUMN changed_at TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN personal_reason VARCHAR(200),
    ADD COLUMN reason_source VARCHAR(10);

-- 이미 있는 관광지 항목: 자동 추천은 기준점(BASE), 수동은 누가 넣었는지 모르는 추가(ADDED)로 본다.
UPDATE course_items SET origin = CASE WHEN source = 'MANUAL' THEN 'ADDED' ELSE 'BASE' END WHERE kind = 'ATTRACTION';
UPDATE course_items SET reason_source = 'RULE' WHERE kind = 'ATTRACTION' AND reason IS NOT NULL;

ALTER TABLE course_items
    ADD CONSTRAINT ck_course_items_origin CHECK (
        (kind = 'ATTRACTION' AND origin IN ('BASE', 'ADDED', 'REPLACED'))
        OR (kind = 'MEAL' AND origin IS NULL)
    ),
    ADD CONSTRAINT ck_course_items_reason_source CHECK (reason_source IS NULL OR reason_source IN ('RULE', 'LLM'));

COMMENT ON COLUMN course_items.origin IS 'BASE: 기준점 코스(생성·재생성) 항목, ADDED: 기준점 이후 추가, REPLACED: 기준점 이후 교체';
COMMENT ON COLUMN course_items.changed_by_nickname IS '추가·교체한 사람의 닉네임 스냅샷. 탈퇴·강퇴 뒤에도 기록에 남긴다';
COMMENT ON COLUMN course_items.personal_reason IS 'AI 장소 이유 중 취향 기준 회원(taste_basis_user) 본인에게만 보이는 문장';

-- 기준점 이후 지운 관광지. 되살리면 restored_at을 채운다. 재생성하면 모두 지운다(새 기준점).
CREATE TABLE course_removals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_plan_id BIGINT NOT NULL REFERENCES trip_plans(id) ON DELETE CASCADE,
    attraction_id BIGINT REFERENCES attractions(id) ON DELETE SET NULL,
    attraction_name VARCHAR(255) NOT NULL,
    day_index INTEGER NOT NULL,
    origin VARCHAR(20) NOT NULL,
    removed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    removed_by_nickname VARCHAR(50),
    note VARCHAR(100),
    removed_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    restored_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT ck_course_removals_origin CHECK (origin IN ('BASE', 'ADDED', 'REPLACED')),
    CONSTRAINT ck_course_removals_day CHECK (day_index >= 0)
);
CREATE INDEX idx_course_removals_trip ON course_removals(trip_plan_id) WHERE restored_at IS NULL;

ALTER TABLE trip_plans
    ADD COLUMN course_baseline_at TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN course_intro TEXT,
    ADD COLUMN course_intro_source VARCHAR(10),
    ADD CONSTRAINT ck_trip_plans_intro_source CHECK (course_intro_source IS NULL OR course_intro_source IN ('RULE', 'LLM'));

UPDATE trip_plans SET course_baseline_at = course_first_generated_at WHERE course_first_generated_at IS NOT NULL;

-- 3) 지역 × 성향 맞춤 문장 -----------------------------------------------------------------------------------
-- 표시용 AI 문장 캐시. 근거(지역 태그·한 줄 소개·대표 관광지)가 바뀌면 source_hash가 달라져 새로 만든다.
CREATE TABLE region_match_texts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id VARCHAR(5) NOT NULL REFERENCES regions(sig_cd) ON DELETE CASCADE,
    mbti_code VARCHAR(4) NOT NULL,
    text VARCHAR(400) NOT NULL,
    text_source VARCHAR(10) NOT NULL,
    source_hash CHAR(64) NOT NULL,
    generator_model VARCHAR(100),
    prompt_version VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_region_match_texts UNIQUE (region_id, mbti_code),
    CONSTRAINT ck_region_match_texts_mbti CHECK (mbti_code ~ '^[EI][SN][TF][JP]$'),
    CONSTRAINT ck_region_match_texts_source CHECK (text_source IN ('RULE', 'LLM'))
);
